#Operadores aritméticos

x=5
y=10

#suma
print("Suma:", x+y)

#resta
print("Resta:", x-y)

#multiplicacion
print("Multiplicación:", x*y)

#division
print("División:", y/x)

#Modulo
print("Modulo:", y%x)
# El modulo se refiere al residuo de una división, es decir, el resto que queda después de dividir un número por otro. Por ejemplo, en el caso de 12 % 5, el resultado es 2, ya que 5 cabe en 12 dos veces (5*2=10) y sobra un residuo de 2.

#Potencia
print("Potencia:", y**x) #10*10*10*10*10

#Division
print("Division entera:", y//x)


# Ejemplo numero par
par = 8
print(par % 2 == 0)

