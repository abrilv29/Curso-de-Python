# String
comillasSimples = 'Hola, mundo!'
comillasDobles = "Hola, mundo!"
comilasTriple = '''Hola, mundo!'''
comillasDoblesTriple = """Hola, mundo!"""
print(comillasSimples)
print(comillasDobles)
print(comilasTriple)
print(comillasDoblesTriple)

# Numeros
a = 1 # enteros
print(a)

b = 1.5 # flotantes(se usa el punto para separar la parte entera de la decimal)
print(b)

c = 5+2j
print(c)

# Listas = coleccione de elementos que tienen una posicion 

lista = [0,1,2,3,4,5] 
print(lista)

#Tuplas = colecciones de elementos que no se pueden modificar
tupla = (0,1,2,3,4,5)
print(tupla)

# Diccionarios = colecciones de elementos que tienen una clave y un valor
diccionario = {"nombre": "Juan", "edad": 30, "ciudad": "Madrid"}
print(diccionario)

#conjuntos = colecciones de elementos que no se pueden repetir (sets)
conjunto = {1, 1, 3, 4, 5}      
print(conjunto)

#Booleanos = True o False
booleanoVerdadero = True
print(booleanoVerdadero)

booleanoFalso = False
print(booleanoFalso)