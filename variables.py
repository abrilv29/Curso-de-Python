# Uso de variables en Python

x = "Esta es una variable" 
print(x)

x = "Uso la misma variable para almacenar otro valor"
print(x)

X = "Uso la misma variable pero en mayúscula"
print(X)

mivariable = "Esta es otra variable"
print(mivariable)

mi_variable = "Esta es otra variable con guión bajo"
print(mi_variable)

_mi_variable = "Esta es otra variable con guión bajo al inicio"
print(_mi_variable)

miVariable = "Esta es otra variable con mayúscula en medio"
print(miVariable)

MIVARIABLE = "Esta es otra variable con mayúscula en medio"
print(MIVARIABLE)

miVariable2 = "Esta es otra variable con número al final"
print(miVariable2)

